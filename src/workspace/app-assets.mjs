export const workspaceAssets = Object.freeze({
  async fetch(input, init) {
    const request = input instanceof Request && init === undefined ? input : new Request(input, init);
    const path = new URL(request.url).pathname, record = workspaceAssetManifest[path];
    if (!record) return new Response("Not found", {status: 404, headers: {"Cache-Control": "no-store"}});
    if (request.method !== "GET" && request.method !== "HEAD")
      return new Response("Method not allowed", {status: 405, headers: {Allow: "GET, HEAD", "Cache-Control": "no-store"}});
    const etag = "\"" + record.sha256 + "\"";
    const headers = new Headers({"Content-Type": record.contentType, "Content-Length": String(record.bytes),
      "X-Content-Type-Options": "nosniff", ETag: etag,
      "Cache-Control": record.immutable ? "public, max-age=31536000, immutable" : "private, no-cache"});
    if (record.immutable) { headers.set("Access-Control-Allow-Origin", "*"); headers.set("Cross-Origin-Resource-Policy", "cross-origin"); }
    if ((request.headers.get("If-None-Match") || "").split(",").some(value => value.trim().replace(/^W\//, "") === etag || value.trim() === "*")) {
      headers.delete("Content-Length");
      return new Response(null, {status: 304, headers});
    }
    return new Response(request.method === "HEAD" ? null : bodies[path], {headers});
  }
});
